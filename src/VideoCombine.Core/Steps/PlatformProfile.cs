namespace VideoCombine.Core.Steps;

/// <summary>
/// Готовий пресет платформи (розділ 7.5): роздільність + формат кадру, що
/// накладається на склейку. Замість ручного виставляння W/H під кожну соцмережу.
///
/// Параметри платформ змінюються з часом — тримаємо їх тут, у редагованому
/// списку, а не «зашитими» по коду. Редаговані ВЛАСНІ профілі (JSON-store як
/// рецепти) — окремий слайс на потім; поки набір фіксований.
///
/// <paramref name="FitMode"/> — як вписати кадр джерела у цільовий формат:
///   • "fit"  — letterbox (вписати повністю, чорні поля). Норм для 16:9.
///   • "crop" — заповнити кадр і обрізати краї (без полів). Дефолт для
///              вертикальних 9:16, бо letterbox дав би тонку смужку відео.
/// </summary>
public sealed record PlatformProfile(string Name, int Width, int Height, int Fps, string FitMode)
{
    /// <summary>
    /// Вбудовані пресети. Перший — універсальний дефолт. Горизонтальні (Універсальний
    /// і YouTube) поки дають однаковий вихід 1080p/16:9 — YouTube лишено окремо під
    /// майбутні параметри (до 4K, довге відео). Усі вертикальні платформи (Shorts/
    /// TikTok/Reels) за форматом ідентичні, тож тут один профіль; розділимо, коли
    /// додамо платформні обмеження (тривалість тощо).
    /// </summary>
    public static IReadOnlyList<PlatformProfile> All { get; } = new[]
    {
        new PlatformProfile("Універсальний 16:9 1080p",            1920, 1080, 30, "fit"),
        new PlatformProfile("YouTube 16:9 1080p",                  1920, 1080, 30, "fit"),
        new PlatformProfile("Вертикальне 9:16 (Shorts/TikTok/Reels)", 1080, 1920, 30, "crop")
    };

    /// <summary>Дефолтний профіль (універсальний 16:9 1080p).</summary>
    public static PlatformProfile Default => All[0];
}
